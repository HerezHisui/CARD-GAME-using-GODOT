ALIASES = {
    "brace": "armored", "extract": "move", "move_ally": "move", "seal": "sealed",
    "sluggish": "resting", "rally": "strength",
    "on_play_draw": "draw",
}


def main():
    destination = ROOT / "assets" / "symbols"
    destination.mkdir(parents=True, exist_ok=True)
    for name, rows in GLYPHS.items():
        top = (12 - len(rows)) // 2
        left = (12 - max(map(len, rows))) // 2
        pixels = [f'<rect x="{2*(left+x)}" y="{2*(top+y)}" width="2" height="2"/>'
                  for y, row in enumerate(rows) for x, cell in enumerate(row) if cell == "#"]
        svg = ('<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" '
               'viewBox="0 0 24 24"><g fill="#ffffff">' + ''.join(pixels) + '</g></svg>\n')
        (destination / f"{name}.svg").write_text(svg, encoding="utf-8")
    runtime_keys = set()

    def collect(value):
        if isinstance(value, dict):
            for field, item in value.items():
                if field in ("modifier", "effect", "on_sacrifice") and isinstance(item, str):
                    runtime_keys.add(item)
                elif field == "modifiers" and isinstance(item, list):
                    runtime_keys.update(item)
                elif field == "on_hit" and isinstance(item, dict):
                    runtime_keys.update(item)
                collect(item)
        elif isinstance(value, list):
            for item in value:
                collect(item)

    for data_file in (ROOT / "data").glob("*.json"):
        collect(json.loads(data_file.read_text(encoding="utf-8-sig")))
    assert runtime_keys <= GLYPHS.keys() | ALIASES.keys(), runtime_keys - GLYPHS.keys() - ALIASES.keys()
    inventory = {"size": [24, 24], "palette": ["transparent", "white (runtime tint)"],
                 "symbols": sorted(GLYPHS), "aliases": ALIASES,
                 "runtime_data_keys": sorted(runtime_keys),
                 "reference": "Downloads/reference for atk and status.png",
                 "inventory_source": "Downloads/midnight_card_symbols_v1.zip"}
    (destination / "inventory.json").write_text(json.dumps(inventory, indent=2) + '\n', encoding="utf-8")


if __name__ == "__main__":
    main()
